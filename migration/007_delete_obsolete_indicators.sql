-- 007_delete_obsolete_indicators.sql
-- Удаление устаревших/необновляемых индикаторов
--
-- 3.14  Квартирография возводимого жилья (жилая площадь)   — 3 точки, нет источника
-- 3.16  Квартирография возводимого жилья (структура)        — 3 точки, нет источника
-- 5.4   Активность спроса на вторичном рынке               — 6 точек, parсер не реализован
-- 6.28  Всего одобрено заявок за период                    — DomClick, парсер не реализован
-- 6.29  Доля онлайн-заявок за период                       — DomClick, парсер не реализован
-- 6.30  Доля заявок (первичка)                             — DomClick, парсер не реализован
-- 6.31  Доля заявок (вторичка)                             — DomClick, парсер не реализован
-- 6.32  Всего ипотечных сделок за период                   — DomClick, парсер не реализован
-- 6.33  Доля ипотечных сделок (первичка)                   — DomClick, парсер не реализован
-- 6.34  Доля ипотечных сделок (вторичка)                   — DomClick, парсер не реализован
-- 6.35  Доля ипотеки в кредитах населению (устаревший)     — 14 точек до нояб 2022
--
-- Ни один из этих индикаторов не используется на комбо-страницах.

BEGIN;

-- 1. Удаляем data_points
DELETE FROM data_points
WHERE indicator_id IN (
    SELECT id FROM indicators
    WHERE code IN (
        '3.14', '3.16',
        '5.4',
        '6.28', '6.29', '6.30', '6.31', '6.32', '6.33', '6.34', '6.35'
    )
);

-- 2. Удаляем индикаторы
DELETE FROM indicators
WHERE code IN (
    '3.14', '3.16',
    '5.4',
    '6.28', '6.29', '6.30', '6.31', '6.32', '6.33', '6.34', '6.35'
);

COMMIT;
